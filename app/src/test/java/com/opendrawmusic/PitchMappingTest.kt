package com.opendrawmusic

import org.junit.Assert.assertEquals
import org.junit.Test

class PitchMappingTest {
    @Test
    fun cMajorPentatonicMatchesAll32Rows() {
        val expected = listOf(
            84, 84, 81, 81, 79, 79, 76, 76,
            74, 74, 72, 72, 69, 69, 67, 67,
            64, 64, 62, 62, 60, 60, 57, 57,
            55, 55, 52, 52, 50, 50, 48, 48
        )

        assertEquals(expected, (0 until 32).map { midiForRow(it, 48, "PENTATONIC") })
    }

